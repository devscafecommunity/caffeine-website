#!/usr/bin/env python3
"""Generates the Lua API reference pages from the engine's binding descriptions.

Source of truth: `src/caffeine/script/api/<namespace>.json` in the engine repo (one file per Lua namespace, with
English and Portuguese text for every function and parameter). This script writes one page per namespace into
`content/en/docs/scripting/api/` and `content/pt/docs/scripting/api/`. The pages are generated: edit the JSON and
rerun the script instead of editing the Markdown.

    python3 scripts/generate-api-pages.py          # write the pages
    python3 scripts/generate-api-pages.py --check  # exit 1 when a page is missing or out of date
"""
import json
import pathlib
import sys

WEBSITE = pathlib.Path(__file__).resolve().parent.parent
ENGINE_API = WEBSITE.parent / "src" / "caffeine" / "script" / "api"
OUT = {
    "en": WEBSITE / "content" / "en" / "docs" / "scripting" / "api",
    "pt": WEBSITE / "content" / "pt" / "docs" / "scripting" / "api",
}

LABELS = {
    "en": {
        "functions": "Functions",
        "params": "Parameters",
        "returns": "Returns",
        "example": "Example",
        "param": "Parameter",
        "type": "Type",
        "description": "Description",
        "generated": "Generated from",
        "badge": "Reference",
    },
    "pt": {
        "functions": "Funções",
        "params": "Parâmetros",
        "returns": "Devolve",
        "example": "Exemplo",
        "param": "Parâmetro",
        "type": "Tipo",
        "description": "Descrição",
        "generated": "Gerado a partir de",
        "badge": "Referência",
    },
}


def cell(text):
    """Keeps a value on one table row: no pipes, no newlines."""
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def render(lang, data, source_name):
    labels = LABELS[lang]
    title = data.get("title", {}).get(lang) or data["namespace"]
    summary = data.get("summary", {}).get(lang, "")
    lines = [
        f"# {title} API",
        "",
        f'<div class="doc-meta"><span class="doc-badge">{labels["badge"]}</span> '
        f"{labels['generated']} <code>src/caffeine/script/api/{source_name}</code></div>",
        "",
        f"{summary}",
        "",
        f"<!-- Generated by caffeine-website/scripts/generate-api-pages.py. Edit the engine JSON instead. -->",
        "",
        f"## {labels['functions']}",
        "",
    ]
    for fn in data.get("functions", []):
        lines += [f"### `{fn['lua']}`", "", f"`{fn['signature']}`", "", fn.get(lang, ""), ""]
        params = fn.get("params", [])
        if params:
            lines += [
                f"**{labels['params']}**",
                "",
                f"| {labels['param']} | {labels['type']} | {labels['description']} |",
                "|---|---|---|",
            ]
            for p in params:
                lines.append(f"| `{cell(p['name'])}` | {cell(p['type'])} | {cell(p.get(lang, ''))} |")
            lines.append("")
        ret = fn.get("returns")
        if ret:
            lines += [f"**{labels['returns']}:** `{ret['type']}` — {ret.get(lang, '')}", ""]
        example = fn.get("example")
        if example:
            lines += [f"**{labels['example']}**", "", "```lua", example, "```", ""]
    return "\n".join(lines).rstrip() + "\n"


def main(argv):
    check = "--check" in argv
    stale = []
    for source in sorted(ENGINE_API.glob("*.json")):
        data = json.loads(source.read_text(encoding="utf-8"))
        namespace = data["namespace"]
        for lang, folder in OUT.items():
            target = folder / f"{namespace}.md"
            text = render(lang, data, source.name)
            if check:
                if not target.is_file() or target.read_text(encoding="utf-8") != text:
                    stale.append(str(target.relative_to(WEBSITE)))
                continue
            folder.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
    if check and stale:
        print("out of date:\n  " + "\n  ".join(stale))
        return 1
    if not check:
        print(f"wrote {len(list(ENGINE_API.glob('*.json')))} namespaces in en and pt")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
